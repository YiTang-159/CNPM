#!/usr/bin/env node
// Generates a self-contained SSMS migration script from the EXACT canonical files.
// Uses sp_executesql to preserve GO and CREATE VIEW/TRIGGER batch boundaries.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
import { MIGRATIONS, splitBatches, versionFor } from '../../server/src/migrationPlan.mjs';
const dir=resolve(dirname(fileURLToPath(import.meta.url)),'../migrations');
const chunks=[`-- GENERATED BY: node db/scripts/export-ssms.mjs; do not hand-edit.
-- Backup existing DB and verify integrity-audit before applying.
-- Connect to your MIGRATION ADMIN account, NOT the runtime app account.
-- SSMS: select the target database (e.g., DubchefDB or a restored STAGING copy)
-- from the database dropdown BEFORE executing. No USE or CREATE DATABASE here.
IF DB_NAME() IN (N'master',N'model',N'msdb',N'tempdb')
 THROW 51900,N'Select a Dubchef target DB in SSMS, never a system database.',1;
PRINT N'Target database: '+DB_NAME();
GO
SET NOCOUNT ON;
IF OBJECT_ID(N'dbo.SchemaMigrations',N'U') IS NULL
 CREATE TABLE dbo.SchemaMigrations(Version INT NOT NULL CONSTRAINT PK_SchemaMigrations PRIMARY KEY,
 FileName NVARCHAR(100) NOT NULL,AppliedAt DATETIME2(0) NOT NULL
 CONSTRAINT DF_SchemaMigrations_AppliedAt DEFAULT SYSUTCDATETIME(),
 ChecksumSha256 CHAR(64) NULL,AppliedBy NVARCHAR(128) NULL);
IF COL_LENGTH('dbo.SchemaMigrations','ChecksumSha256') IS NULL ALTER TABLE dbo.SchemaMigrations ADD ChecksumSha256 CHAR(64) NULL;
IF COL_LENGTH('dbo.SchemaMigrations','AppliedBy') IS NULL ALTER TABLE dbo.SchemaMigrations ADD AppliedBy NVARCHAR(128) NULL;
GO
`];
function sqlExpression(s) {
  // SQL Server N'...' string literals must remain under NVARCHAR(4000) to avoid truncation.
  const chunks=[];for(let i=0;i<s.length;i+=900)chunks.push("N'"+s.slice(i,i+900).replace(/'/g,"''")+"'");
  return 'CONVERT(NVARCHAR(MAX),'+chunks[0]+')'+chunks.slice(1).map(x=>' +\n    '+x).join('');
}
for(const name of MIGRATIONS) {
 const version=versionFor(name),source=await readFile(join(dir,name),'utf8');
 const hash=createHash('sha256').update(source).digest('hex');
 chunks.push(`-- ${name} SHA256 ${hash}\nBEGIN TRY
 BEGIN TRAN;
 DECLARE @gotLock INT,@apply BIT=1,@existing CHAR(64),@oldName NVARCHAR(100),@stmt NVARCHAR(MAX);
 EXEC @gotLock=sys.sp_getapplock @Resource=N'DubchefDB:SchemaMigrations',@LockMode=N'Exclusive',@LockOwner=N'Transaction',@LockTimeout=30000;
 IF @gotLock<0 THROW 51901,N'Failed to acquire schema migration lock',1;
 SELECT @existing=ChecksumSha256,@oldName=FileName FROM dbo.SchemaMigrations WITH(UPDLOCK,HOLDLOCK) WHERE Version=${version};
 IF @existing IS NOT NULL BEGIN
  IF @existing<>'${hash}' THROW 51902,N'Migration checksum mismatch',1;
  SET @apply=0;
 END
 ELSE IF @oldName IS NOT NULL AND NOT (${version}=14 AND @oldName=N'014_pricing.sql')
  THROW 51903,N'Unknown legacy migration entry; manual review required',1;
 IF @apply=1 BEGIN\n`);
 for(const batch of splitBatches(source)) {
  chunks.push(`  SET @stmt = ${sqlExpression(batch)};\n  EXEC sys.sp_executesql @stmt;\n`);
 }
 chunks.push(`  IF EXISTS(SELECT 1 FROM dbo.SchemaMigrations WHERE Version=${version})
   UPDATE dbo.SchemaMigrations SET FileName=N'${name}',ChecksumSha256='${hash}',AppliedBy=SUSER_SNAME() WHERE Version=${version};
  ELSE INSERT dbo.SchemaMigrations(Version,FileName,ChecksumSha256,AppliedBy)
   VALUES(${version},N'${name}','${hash}',SUSER_SNAME());
 END
 COMMIT;
 PRINT N'${name}: OK';
END TRY
BEGIN CATCH
 IF @@TRANCOUNT>0 ROLLBACK;
 THROW;
END CATCH;
GO\n`);
}
const out=join(dir,'RUN_ALL_IN_SSMS.sql');await writeFile(out,chunks.join('\n'));
console.log(`SSMS script: ${out} (${MIGRATIONS.length} migrations; SHA-256 verified)`);
